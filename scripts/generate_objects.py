#!/usr/bin/env python3
"""Generate the object models and the world's object block from aibot_gazebo/config/objects.yaml.

Writes
  src/aibot_gazebo/models/<model>/{model.sdf, model.config}   one per entry in `models`
  src/aibot_gazebo/worlds/pick_table.sdf                       the block between the
                                                               GENERATED-OBJECTS markers
Why a generator: inertia tensors are computed from shape and mass (solid box, cylinder about its
axis, sphere), so none can violate the triangle inequality, and the world's slot list cannot
drift from the YAML. Every graspable model carries a PosePublisher (named poses for evaluation
and the grasp weld shim; perception never uses them).

Usage:  python3 scripts/generate_objects.py
"""
from __future__ import annotations

import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1] / "src" / "aibot_gazebo"
BEGIN, END = "<!-- BEGIN GENERATED-OBJECTS", "<!-- END GENERATED-OBJECTS -->"

POSE_PUBLISHER = """    <plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher">
      <publish_model_pose>true</publish_model_pose>
      <publish_link_pose>false</publish_link_pose>
      <publish_nested_model_pose>false</publish_nested_model_pose>
      <use_pose_vector_msg>true</use_pose_vector_msg>
      <update_frequency>30</update_frequency>
    </plugin>"""


def inertia(m: dict) -> tuple[float, float, float]:
    mass = m["mass"]
    if m["shape"] == "box":
        x, y, z = m["size"]
        return mass * (y * y + z * z) / 12, mass * (x * x + z * z) / 12, mass * (x * x + y * y) / 12
    if m["shape"] == "cylinder":
        r, h = m["radius"], m["length"]
        i = mass * (3 * r * r + h * h) / 12
        return i, i, mass * r * r / 2
    if m["shape"] == "sphere":
        i = 0.4 * mass * m["radius"] ** 2
        return i, i, i
    raise ValueError(m["shape"])


def geometry(m: dict) -> str:
    if m["shape"] == "box":
        return f"<box><size>{' '.join(f'{v:g}' for v in m['size'])}</size></box>"
    if m["shape"] == "cylinder":
        return f"<cylinder><radius>{m['radius']:g}</radius><length>{m['length']:g}</length></cylinder>"
    return f"<sphere><radius>{m['radius']:g}</radius></sphere>"


def material(m: dict) -> str:
    r, g, b = m["rgb"]
    return (f"<material><ambient>{0.8 * r:.3f} {0.8 * g:.3f} {0.8 * b:.3f} 1</ambient>"
            f"<diffuse>{r:g} {g:g} {b:g} 1</diffuse><specular>0.2 0.2 0.2 1</specular></material>")


def half_height(m: dict) -> float:
    """Distance from the model origin down to its resting face."""
    if m["shape"] in ("box",):
        return m["size"][2] / 2
    if m["shape"] == "cylinder":
        return m["length"] / 2
    if m["shape"] == "sphere":
        return m["radius"]
    return 0.0                                   # bin / tray: origin on their bottom face


def graspable_sdf(name: str, m: dict) -> str:
    ixx, iyy, izz = inertia(m)
    surface = (f"<surface><friction><ode><mu>{m['mu']:g}</mu><mu2>{m['mu']:g}</mu2></ode></friction>"
               "<contact><ode><min_depth>0.001</min_depth></ode></contact></surface>")
    return f"""<?xml version="1.0"?>
<!-- GENERATED by scripts/generate_objects.py from config/objects.yaml - DO NOT EDIT.
     {m['color']} {m['shape']}, {m['mass']} kg; inertia of a solid {m['shape']} about its centre. -->
<sdf version="1.9">
  <model name="{name}">
    <link name="link">
      <inertial>
        <mass>{m['mass']:g}</mass>
        <inertia><ixx>{ixx:.4e}</ixx><iyy>{iyy:.4e}</iyy><izz>{izz:.4e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <collision name="collision">
        <geometry>{geometry(m)}</geometry>
        {surface}
      </collision>
      <visual name="visual">
        <geometry>{geometry(m)}</geometry>
        {material(m)}
      </visual>
    </link>
{POSE_PUBLISHER}
  </model>
</sdf>
"""


def container_sdf(name: str, m: dict) -> str:
    sx, sy, sz = m["size"]
    parts = []
    if m["shape"] == "bin":
        w = m["wall"]
        parts = [("floor", (0, 0, w / 2), (sx, sy, w)),
                 ("wall_px", (sx / 2 - w / 2, 0, sz / 2), (w, sy, sz)),
                 ("wall_nx", (-sx / 2 + w / 2, 0, sz / 2), (w, sy, sz)),
                 ("wall_py", (0, sy / 2 - w / 2, sz / 2), (sx - 2 * w, w, sz)),
                 ("wall_ny", (0, -sy / 2 + w / 2, sz / 2), (sx - 2 * w, w, sz))]
    else:
        parts = [("plate", (0, 0, sz / 2), (sx, sy, sz))]
    body = []
    for pname, (px, py, pz), (bx, by, bz) in parts:
        g = f"<box><size>{bx:g} {by:g} {bz:g}</size></box>"
        body.append(f"""      <collision name="{pname}_collision"><pose>{px:g} {py:g} {pz:g} 0 0 0</pose>
        <geometry>{g}</geometry>
        <surface><friction><ode><mu>0.9</mu><mu2>0.9</mu2></ode></friction></surface></collision>
      <visual name="{pname}_visual"><pose>{px:g} {py:g} {pz:g} 0 0 0</pose>
        <geometry>{g}</geometry>{material(m)}</visual>""")
    return f"""<?xml version="1.0"?>
<!-- GENERATED by scripts/generate_objects.py from config/objects.yaml - DO NOT EDIT.
     {m['color']} {m['shape']} {sx:g} x {sy:g} x {sz:g} m, static, origin on its bottom face. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="link">
{chr(10).join(body)}
    </link>
{POSE_PUBLISHER}
  </model>
</sdf>
"""


def model_config(name: str, m: dict) -> str:
    return f"""<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>{m['color']} {m['shape']} (generated from config/objects.yaml)</description>
</model>
"""


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config" / "objects.yaml").read_text())
    models = cfg["models"]
    for name, m in models.items():
        d = ROOT / "models" / name
        d.mkdir(parents=True, exist_ok=True)
        sdf = container_sdf(name, m) if m["shape"] in ("bin", "tray") else graspable_sdf(name, m)
        (d / "model.sdf").write_text(sdf)
        (d / "model.config").write_text(model_config(name, m))
    top = cfg["table"]["top_z"]
    slots = {**cfg["slots"]["graspable"], **cfg["slots"]["containers"]}
    layout = cfg["default_layout"]
    ox, oy = cfg["parking"]["origin"]
    lines = [f"{BEGIN}: scripts/generate_objects.py from config/objects.yaml - DO NOT EDIT.",
             "         Slots on the table follow default_layout; the others are parked behind the robot. -->"]
    parked = 0
    for slot, model in slots.items():
        m = models[model]
        if slot in layout:
            x, y, yaw = layout[slot]
            z = top + half_height(m) + 0.001
        else:
            x, y, yaw = ox - parked * cfg["parking"]["spacing"], oy, 0.0
            z = half_height(m) + 0.001
            parked += 1
        lines.append(f"    <include><name>{slot}</name><uri>model://{model}</uri>"
                     f"<pose>{x:.3f} {y:.3f} {z:.4f} 0 0 {yaw:.3f}</pose></include>")
    lines.append(f"    {END}")
    world = ROOT / "worlds" / "pick_table.sdf"
    text = world.read_text()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    world.write_text(text[:a] + "\n".join(lines) + text[b:])
    print(f"wrote {len(models)} models, {len(slots)} world slots ({parked} parked)")


if __name__ == "__main__":
    main()
